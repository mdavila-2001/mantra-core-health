/**
 * La provincia de un municipio por el catálogo, o `null` si no se la conoce.
 *
 * Por código del INE si viene uno de seis dígitos; si no (la maqueta siembra
 * códigos legados como `SC-SCZ`), por nombre dentro de su departamento.
 */
export function provinceFromCatalog(sigla: string, ine: string, nombre: string): string | null {
  if (/^\d{6}$/.test(ine)) {
    const porIne = PROVINCIA_POR_INE[ine.slice(0, 4)];
    if (porIne !== undefined) return porIne;
  }
  const buscado = normalizePlace(nombre);
  const municipio = MUNICIPIOS[sigla === 'PA' ? 'PD' : sigla]?.find(
    ([, n]) => normalizePlace(n) === buscado,
  );
  return municipio === undefined ? null : (PROVINCIA_POR_INE[municipio[0].slice(0, 4)] ?? null);
}
