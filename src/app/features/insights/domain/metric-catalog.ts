/* ============================================================================
    Catálogo de métricas — «Principio de gerencia».

    Una métrica entra al catálogo solo si responde: por qué existe, qué decisión
    permite tomar, quién la usa, qué significa si sube y si baja, y qué acción
    debería provocar. Si una fila no puede completar esas columnas, se cuestiona
    su inclusión.

    Redundancias cuestionadas y resueltas:
      · CPA y CAC miden costos distintos. CPA = inversión de medios ÷ conversiones
        (evalúa la pauta). CAC = (medios + producción y comisiones) ÷ usuarios
        activados (evalúa el negocio). CAC se muestra siempre con LTV y LTV/CAC.
      · Alcance NO se suma entre días: se estima el alcance único del periodo.
      · Clics y CTR conviven porque uno es volumen y el otro eficiencia; el
        volumen solo sirve junto a la inversión.
    ========================================================================== */

