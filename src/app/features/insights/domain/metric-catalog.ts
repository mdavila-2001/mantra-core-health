export const ALL_METRICS: readonly MetricDefinition[] = METRIC_IDS.map((id) => METRIC_CATALOG[id]);

/** Una métrica solo se admite si completa las columnas del principio de gerencia. */
export function isCompleteDefinition(def: MetricDefinition): boolean {
  return [def.definition, def.decision, def.ifUp, def.ifDown, def.action, def.owner].every(
    (text) => text.trim().length > 0,
  );
}
